#!/usr/bin/env python3
"""Regenerate the parameterized Rust LayerTree MID Script fragments.

Usage: python3 contrib/generate_layertree_fragments.py UPSTREAM_CHECKOUT
       [--check]

The only inputs are the BSD-3-Clause LayerTree v0.15.2 generators at
https://github.com/roasbeef/layertree/commit/f64cc0e4d4471e32f7fd8294ecb0b1c7547c1166
The generated Rust has no Python dependency. Runtime parameters remain
typed pushes, and path levels remain a bounded runtime repetition.
"""
import argparse
import hashlib
import importlib
from pathlib import Path
import subprocess
import sys

SOURCES = {
    "layertree_ref.py": "583f0dde0765075ff16f44340e0f7cf65102a69d86dff8b54459017461c8b6cb",
    "layertree_scripts.py": "06218d0e206f7e3db6196d6b9e482fc94c234255d9bdccc00b1ae8dd5799422f",
    "layertree_mid.py": "8eb3ec93793f3a5f95942a7c4c75eb8208712c5f678ffbf8230a9bb55a35ffe7",
    "script_sim.py": "5289bcf9d5be275d24d1e33a3552287e1ca5ed63a0cd91129a0044cf76e05532",
}


class Parameter(bytes):
    def __new__(cls, expression):
        obj = super().__new__(cls, bytes(32))
        obj.expression = expression
        return obj


class Number(int):
    pass


class Levels:
    def __init__(self, height):
        self.height = height


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--rustfmt", default="rustfmt")
    args = parser.parse_args()
    directory = args.upstream / "tools"
    for filename, expected in SOURCES.items():
        actual = hashlib.sha256((directory / filename).read_bytes()).hexdigest()
        if actual != expected:
            parser.error(f"source mismatch: {filename}")
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(directory.resolve()))
    mid = importlib.import_module("layertree_mid")
    reference = importlib.import_module("layertree_ref")
    sim = importlib.import_module("script_sim")
    old_empty = reference.empty_node
    reference.empty_node = lambda height: (
        (Parameter("&Node::empty(config.depth).hash"), 0)
        if height == 16 else old_empty(height)
    )
    level_tokens = mid.level(False)
    mid.levels = lambda sparse, depth, height=0: [Levels(height)]
    operator = Parameter("&config.operator.serialize()")
    tree_id = Parameter("&config.tree_id")
    dust = Number(330)
    scripts = {
        "exit_1": mid.exit_script(16),
        "exit_2": mid.exit_script(16, k=2),
        "join_0": mid.join_script(16, 0, operator),
        "join_2": mid.join_script(16, 2, operator),
        "update": mid.update_script(16, operator),
        "claim": mid.claim_script(16, tree_id, dust_min=dust),
        "claim_hashlock": mid.claim_script(16, tree_id, hashlock=True, dust_min=dust),
        "split": mid.split_script(16, dust_min=dust),
        "sweep_1": mid.evict_subtree_script(16, 1, operator),
        "sweep_2": mid.evict_subtree_script(16, 2, operator),
        "rewrite_2": mid.rewrite_script(16, 2, operator),
    }
    output = [
        "// Generated by contrib/generate_layertree_fragments.py. Do not edit.",
        "// LayerTree v0.15.2, BSD-3-Clause; upstream commit:",
        "// f64cc0e4d4471e32f7fd8294ecb0b1c7547c1166.",
        "// Opcode bytes are the pinned draft profile, including placeholders.",
        "use super::{push_data, push_number, Config};",
        "use super::super::tree::Node;",
        "",
    ]

    def fixed(blob, indent="    "):
        if not blob:
            return
        output.append(indent + "out.extend_from_slice(&[")
        for i in range(0, len(blob), 16):
            output.append(indent + "    " + ", ".join(f"0x{x:02x}" for x in blob[i:i + 16]) + ",")
        output.append(indent + "]);")

    for name, tokens in scripts.items():
        output.append(f"pub(super) fn {name}(config: &Config) -> Vec<u8> {{")
        output.append("    let mut out = Vec::new();")
        blob = bytearray()
        for token in tokens:
            if isinstance(token, (Parameter, Number, Levels)):
                fixed(blob)
                blob.clear()
                if isinstance(token, Parameter):
                    output.append(f"    push_data(&mut out, {token.expression});")
                elif isinstance(token, Number):
                    output.append("    push_number(&mut out, config.dust_min as i64);")
                else:
                    output.append(f"    for _ in {token.height}..config.depth {{")
                    fixed(sim.assemble(level_tokens, mode="c0"), "        ")
                    output.append("    }")
            else:
                blob += sim.assemble([token], mode="c0")
        fixed(blob)
        output.extend(["    out", "}", ""])
    text = subprocess.run(
        [args.rustfmt, "--edition", "2021", "--emit", "stdout"],
        input="\n".join(output), text=True, check=True, capture_output=True,
    ).stdout
    destination = Path(__file__).resolve().parents[1] / "sapio-contrib/src/contracts/layertree/script_fragments.rs"
    if args.check:
        if destination.read_text() != text:
            parser.error("generated Script fragments are stale")
    else:
        destination.write_text(text)


if __name__ == "__main__":
    main()
